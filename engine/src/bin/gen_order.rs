//! Generates `src/preflop_order.rs`: the 169 hand classes ordered by average
//! Monte Carlo all-in equity against 1, 2 and 3 random hands.
//! Usage: gen_order TRIALS THREADS > src/preflop_order.rs

use poker_engine::combos::{class_combos, class_name};
use poker_trainer::cards::Card;
use poker_trainer::eval::evaluate;
use poker_trainer::rng::Rng;
use std::sync::atomic::{AtomicUsize, Ordering};
use std::sync::Mutex;

fn rep(class: usize) -> (Card, Card) {
    if class < 13 {
        (Card::new(class as u8, 0), Card::new(class as u8, 1))
    } else {
        let (suited, tri) = if class < 91 { (true, class - 13) } else { (false, class - 91) };
        let mut high = 1usize;
        while high * (high + 1) / 2 <= tri {
            high += 1;
        }
        let low = tri - high * (high - 1) / 2;
        let a = Card::new(high as u8, 0);
        let b = Card::new(low as u8, if suited { 0 } else { 1 });
        (a, b)
    }
}

fn equity_vs_random(class: usize, trials: u64, seed: u64) -> f64 {
    let (a, b) = rep(class);
    let dead = a.mask() | b.mask();
    let deck: Vec<Card> = (0..52u8).map(Card::from_index).filter(|c| c.mask() & dead == 0).collect();
    let mut rng = Rng::new(seed);
    let mut total = 0.0;
    for t in 0..trials {
        let villains = (t % 3) as usize + 1;
        let need = 5 + 2 * villains;
        // Partial Fisher-Yates over a working copy.
        let mut d = deck.clone();
        for i in 0..need {
            let j = i + rng.below((d.len() - i) as u64) as usize;
            d.swap(i, j);
        }
        let board = &d[..5];
        let cards = [a, b, board[0], board[1], board[2], board[3], board[4]];
        let me = evaluate(&cards);
        let mut hero_lost = false;
        let mut ties = 0;
        for v in 0..villains {
            let h = [d[5 + 2 * v], d[6 + 2 * v]];
            let c = [h[0], h[1], board[0], board[1], board[2], board[3], board[4]];
            let r = evaluate(&c);
            if r > me {
                hero_lost = true;
                break;
            }
            if r == me {
                ties += 1;
            }
        }
        if !hero_lost {
            total += 1.0 / f64::from(1 + ties);
        }
    }
    total / trials as f64
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let trials: u64 = args.get(1).map_or(3_000_000, |s| s.parse().expect("trials"));
    let threads: usize = args.get(2).map_or(30, |s| s.parse().expect("threads"));
    let next = AtomicUsize::new(0);
    let results = Mutex::new(vec![0f64; 169]);
    std::thread::scope(|sc| {
        for _ in 0..threads {
            sc.spawn(|| loop {
                let c = next.fetch_add(1, Ordering::SeqCst);
                if c >= 169 {
                    break;
                }
                let e = equity_vs_random(c, trials, 0x9000 + c as u64);
                results.lock().unwrap()[c] = e;
            });
        }
    });
    let eq = results.into_inner().unwrap();
    let mut order: Vec<usize> = (0..169).collect();
    order.sort_by(|&a, &b| eq[b].partial_cmp(&eq[a]).unwrap());
    println!("//! Generated by src/bin/gen_order.rs: {trials} trials per class, equity vs 1/2/3 random hands, strongest first.");
    println!("//! Do not edit by hand. Order: {}", order.iter().map(|&c| class_name(c)).collect::<Vec<_>>().join(" "));
    println!();
    println!("pub const ORDER: [u8; 169] = [");
    for chunk in order.chunks(16) {
        let line: Vec<String> = chunk.iter().map(|c| c.to_string()).collect();
        println!("    {},", line.join(", "));
    }
    println!("];");
    let combos: u32 = order.iter().map(|&c| class_combos(c)).sum();
    eprintln!("combos counted: {combos}");
}
